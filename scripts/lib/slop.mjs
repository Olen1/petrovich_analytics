/** Найти маркеры. Код и диаграммы (```…```) не проверяются. */
export function scanSlop(text) {
  const hits = [];
  let inCode = false;
  let words = 0;
  text.split(/\r?\n/).forEach((line, i) => {
    if (/^\s*```/.test(line)) { inCode = !inCode; return; }
    if (inCode) return;
    words += line.split(/\s+/).filter(Boolean).length;
    for (const rule of RULES) {
      rule.re.lastIndex = 0;
      for (const m of line.matchAll(rule.re)) hits.push({ line: i + 1, col: m.index + 1, id: rule.id, level: rule.level, hint: rule.hint, text: m[0] });
    }
  });
  const soft = hits.filter((h) => h.level === "soft").length;
  hits.sort((a, b) => a.line - b.line || a.col - b.col);
  return { hits, words, softPer1k: words ? (soft * 1000) / words : 0 };
}
